CREATE TABLE SEARCH_SESSIONS (
    SEARCH_ID           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    USER_ID             NUMBER NOT NULL,
    QUERY_ID            NUMBER NOT NULL,
    SOURCE_TYPE         VARCHAR2(20) NOT NULL,
    VIDEO_ID            NUMBER,
    CAMERA_ID           NUMBER,
    STATUS              VARCHAR2(30) DEFAULT 'QUEUED' NOT NULL,
    PROGRESS_PERCENT    NUMBER(5, 2) DEFAULT 0 NOT NULL,
    STARTED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_AT        TIMESTAMP WITH TIME ZONE,
    ERROR_MESSAGE       VARCHAR2(2000),
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    -- Primary Key Constraint
    CONSTRAINT PK_SEARCH_SESSIONS PRIMARY KEY (SEARCH_ID),
    -- Foreign Keys
    CONSTRAINT FK_SEARCH_SESSIONS_USER FOREIGN KEY (USER_ID)
        REFERENCES APP_USERS (USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_SEARCH_SESSIONS_QUERY FOREIGN KEY (QUERY_ID)
        REFERENCES OBJECT_QUERIES (QUERY_ID) ON DELETE CASCADE,
    CONSTRAINT FK_SEARCH_SESSIONS_VIDEO FOREIGN KEY (VIDEO_ID)
        REFERENCES VIDEO_FILES (VIDEO_ID) ON DELETE SET NULL,
    CONSTRAINT FK_SEARCH_SESSIONS_CAMERA FOREIGN KEY (CAMERA_ID)
        REFERENCES CAMERAS (CAMERA_ID) ON DELETE SET NULL,
    -- Domain Check Constraints
    CONSTRAINT CK_SEARCH_SESSIONS_SOURCE CHECK (SOURCE_TYPE IN ('VIDEO', 'CAMERA')),
    CONSTRAINT CK_SEARCH_SESSIONS_STATUS CHECK (STATUS IN (
        'QUEUED', 'INITIALIZING', 'EXTRACTING_FRAMES',
        'ANALYZING', 'TRACKING', 'VERIFYING',
        'DETECTED', 'NOT_DETECTED', 'FAILED', 'CANCELLED'
    )),
    CONSTRAINT CK_SEARCH_SESSIONS_PROGRESS CHECK (PROGRESS_PERCENT BETWEEN 0 AND 100),
    -- Strict Mutually Exclusive Source Constraint:
    -- If SOURCE_TYPE = 'VIDEO' then VIDEO_ID must be provided and CAMERA_ID must be NULL.
    -- If SOURCE_TYPE = 'CAMERA' then CAMERA_ID must be provided and VIDEO_ID must be NULL.
    CONSTRAINT CK_SEARCH_SESSIONS_SRC_MUTEX CHECK (
        (SOURCE_TYPE = 'VIDEO' AND VIDEO_ID IS NOT NULL AND CAMERA_ID IS NULL) OR
        (SOURCE_TYPE = 'CAMERA' AND CAMERA_ID IS NOT NULL AND VIDEO_ID IS NULL)
    )
);

COMMENT ON TABLE SEARCH_SESSIONS IS 'Core operational search sessions tracking AI detection lifecycle across sources.';
