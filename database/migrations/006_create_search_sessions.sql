COMMENT ON COLUMN SEARCH_SESSIONS.USER_ID IS 'Investigator/operator running the search operation.';
COMMENT ON COLUMN SEARCH_SESSIONS.QUERY_ID IS 'Reference to the descriptive object target in OBJECT_QUERIES.';
COMMENT ON COLUMN SEARCH_SESSIONS.SOURCE_TYPE IS 'VIDEO or CAMERA.';
COMMENT ON COLUMN SEARCH_SESSIONS.STATUS IS 'Finite state machine stage: QUEUED through DETECTED/NOT_DETECTED/FAILED.';
COMMENT ON COLUMN SEARCH_SESSIONS.PROGRESS_PERCENT IS '0.00 to 100.00 completion metric.';
COMMENT ON COLUMN SEARCH_SESSIONS.COMPLETED_AT IS 'Timestamp when terminal state was reached.';
