-- 1. Candidate and Verified Detection Frames Extracted from Footage
CREATE TABLE DETECTION_FRAMES (
    FRAME_ID            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SEARCH_ID           NUMBER NOT NULL,
    FRAME_NUMBER        NUMBER NOT NULL,
    FRAME_TIMESTAMP_MS  NUMBER NOT NULL,
    IMAGE_PATH          VARCHAR2(500) NOT NULL,
    ANALYSIS_STATUS     VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT          TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    -- Primary Key Constraint
    CONSTRAINT PK_DETECTION_FRAMES PRIMARY KEY (FRAME_ID),
    -- Foreign Key Constraint
    CONSTRAINT FK_DETECTION_FRAMES_SEARCH FOREIGN KEY (SEARCH_ID)
        REFERENCES SEARCH_SESSIONS (SEARCH_ID) ON DELETE CASCADE,
    -- Constraints
    CONSTRAINT CK_DETECTION_FRAMES_STATUS CHECK (
        ANALYSIS_STATUS IN ('PENDING', 'PROCESSED', 'MATCH_FOUND', 'SKIPPED')
    ),
    CONSTRAINT CK_DETECTION_FRAMES_NUM CHECK (FRAME_NUMBER >= 0),
    CONSTRAINT CK_DETECTION_FRAMES_TS CHECK (FRAME_TIMESTAMP_MS >= 0)
);

COMMENT ON TABLE DETECTION_FRAMES IS 'Extracted frames and keyframes undergoing computer vision analysis.';
COMMENT ON COLUMN DETECTION_FRAMES.FRAME_ID IS 'Surrogate primary key auto-generated via identity column.';
COMMENT ON COLUMN DETECTION_FRAMES.SEARCH_ID IS 'Foreign key reference to SEARCH_SESSIONS.';
COMMENT ON COLUMN DETECTION_FRAMES.IMAGE_PATH IS 'Relative path to extracted JPEG/WebP frame.';
COMMENT ON COLUMN DETECTION_FRAMES.ANALYSIS_STATUS IS 'Processing state of individual frame.';

-- 2. Identified Objects with Bounding Boxes & Confidence Scores
CREATE TABLE DETECTION_RESULTS (
    DETECTION_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SEARCH_ID           NUMBER NOT NULL,
    OBJECT_NAME         VARCHAR2(100) NOT NULL,
    CONFIDENCE_SCORE    NUMBER(5, 4) NOT NULL,
    CAMERA_ID           NUMBER,
    VIDEO_ID            NUMBER,
    FRAME_NUMBER        NUMBER NOT NULL,
    FRAME_TIMESTAMP_MS  NUMBER NOT NULL,
    BOUNDING_BOX_X      NUMBER(8, 4) NOT NULL,
    BOUNDING_BOX_Y      NUMBER(8, 4) NOT NULL,
    BOUNDING_BOX_WIDTH  NUMBER(8, 4) NOT NULL,
    BOUNDING_BOX_HEIGHT NUMBER(8, 4) NOT NULL,
    IMAGE_PATH          VARCHAR2(500) NOT NULL,
    DETECTED_AT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    VERIFIED            NUMBER(1) DEFAULT 0 NOT NULL,
    -- Primary Key Constraint
    CONSTRAINT PK_DETECTION_RESULTS PRIMARY KEY (DETECTION_ID),
    -- Foreign Keys
    CONSTRAINT FK_DETECTION_RESULTS_SEARCH FOREIGN KEY (SEARCH_ID)
        REFERENCES SEARCH_SESSIONS (SEARCH_ID) ON DELETE CASCADE,
    CONSTRAINT FK_DETECTION_RESULTS_CAMERA FOREIGN KEY (CAMERA_ID)
        REFERENCES CAMERAS (CAMERA_ID) ON DELETE SET NULL,
    CONSTRAINT FK_DETECTION_RESULTS_VIDEO FOREIGN KEY (VIDEO_ID)
        REFERENCES VIDEO_FILES (VIDEO_ID) ON DELETE SET NULL,
    -- Check Constraints
    CONSTRAINT CK_DETECTION_CONFIDENCE CHECK (CONFIDENCE_SCORE BETWEEN 0 AND 1),
    CONSTRAINT CK_DETECTION_VERIFIED CHECK (VERIFIED IN (0, 1)),
    CONSTRAINT CK_DETECTION_BOX_X CHECK (BOUNDING_BOX_X >= 0),
    CONSTRAINT CK_DETECTION_BOX_Y CHECK (BOUNDING_BOX_Y >= 0),
    CONSTRAINT CK_DETECTION_BOX_W CHECK (BOUNDING_BOX_WIDTH > 0),
    CONSTRAINT CK_DETECTION_BOX_H CHECK (BOUNDING_BOX_HEIGHT > 0)
);

COMMENT ON TABLE DETECTION_RESULTS IS 'Positive visual object detections with bounding box geometry and confidence ratings.';
COMMENT ON COLUMN DETECTION_RESULTS.DETECTION_ID IS 'Surrogate primary key auto-generated via identity column.';
COMMENT ON COLUMN DETECTION_RESULTS.CONFIDENCE_SCORE IS 'Normalized AI match confidence from 0.0000 to 1.0000.';
COMMENT ON COLUMN DETECTION_RESULTS.FRAME_TIMESTAMP_MS IS 'Offset in milliseconds from start of media stream.';
COMMENT ON COLUMN DETECTION_RESULTS.BOUNDING_BOX_X IS 'Normalized or pixel horizontal origin coordinate.';
COMMENT ON COLUMN DETECTION_RESULTS.VERIFIED IS 'Boolean flag (0 = Unverified AI hypothesis, 1 = Human verified confirmation).';
