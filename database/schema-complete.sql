-- 1. APP_USERS
CREATE TABLE APP_USERS (
    USER_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    FULL_NAME       VARCHAR2(150) NOT NULL,
    EMAIL           VARCHAR2(255) NOT NULL,
    PASSWORD_HASH   VARCHAR2(255) NOT NULL,
    ROLE            VARCHAR2(20) DEFAULT 'USER' NOT NULL,
    STATUS          VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_LOGIN_AT   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_APP_USERS PRIMARY KEY (USER_ID),
    CONSTRAINT UQ_APP_USERS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_APP_USERS_ROLE CHECK (ROLE IN ('USER', 'ADMIN')),
    CONSTRAINT CK_APP_USERS_STATUS CHECK (STATUS IN ('ACTIVE', 'DISABLED')),
    CONSTRAINT CK_APP_USERS_EMAIL_FMT CHECK (REGEXP_LIKE(EMAIL, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'))
);

